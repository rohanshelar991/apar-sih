package com.infobro.apaar.service;

import com.infobro.apaar.entity.Institution;
import com.infobro.apaar.entity.Programme;
import com.infobro.apaar.entity.Student;
import com.infobro.apaar.entity.ValidationIssue;
import com.infobro.apaar.repository.InstitutionRepository;
import com.infobro.apaar.repository.ProgrammeRepository;
import com.infobro.apaar.repository.StudentRepository;
import com.infobro.apaar.repository.ValidationIssueRepository;
import com.lowagie.text.*;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

@Service
public class ReportService {

    private final InstitutionRepository institutionRepository;
    private final ProgrammeRepository programmeRepository;
    private final StudentRepository studentRepository;
    private final ValidationIssueRepository validationIssueRepository;
    private final AuditService auditService;

    public ReportService(InstitutionRepository institutionRepository,
                         ProgrammeRepository programmeRepository,
                         StudentRepository studentRepository,
                         ValidationIssueRepository validationIssueRepository,
                         AuditService auditService) {
        this.institutionRepository = institutionRepository;
        this.programmeRepository = programmeRepository;
        this.studentRepository = studentRepository;
        this.validationIssueRepository = validationIssueRepository;
        this.auditService = auditService;
    }

    public String generateSummaryCsv(Long institutionId, Integer academicYear, String actor, String role, String ip) {
        StringWriter sw = new StringWriter();
        PrintWriter pw = new PrintWriter(sw);

        pw.println("AICTE APAAR-Connect Institutional Regulatory Summary Report");
        pw.println("Generated At:," + LocalDateTime.now().format(DateTimeFormatter.ISO_LOCAL_DATE_TIME));
        pw.println("Generated By:," + actor + " (" + role + ")");
        pw.println();

        pw.println("--- PROGRAMME INTAKE UTILIZATION ---");
        pw.println("Institution Code,Institution Name,Programme,Approved Intake,Supernumerary,Total Permitted,Actual Enrolment,Utilization %,Status");

        List<Programme> programmes;
        if (institutionId != null) {
            programmes = programmeRepository.findByInstitutionId(institutionId);
        } else {
            programmes = programmeRepository.findAll();
        }

        for (Programme p : programmes) {
            long actual = studentRepository.countByProgrammeId(p.getId());
            double util = p.getTotalPermittedIntake() > 0 ?
                    Math.round((double) actual / p.getTotalPermittedIntake() * 1000.0) / 10.0 : 0.0;
            String status = util > 100.0 ? "EXCEEDED" : (util >= 90.0 ? "WARNING" : "OK");

            pw.printf("\"%s\",\"%s\",\"%s\",%d,%d,%d,%d,%.1f%%,\"%s\"%n",
                    p.getInstitution().getCode(),
                    p.getInstitution().getName(),
                    p.getName(),
                    p.getApprovedIntake(),
                    p.getSupernumeraryQuota(),
                    p.getTotalPermittedIntake(),
                    actual,
                    util,
                    status
            );
        }

        pw.println();
        pw.println("--- REGULATORY EXCEPTIONS & ANOMALIES ---");
        pw.println("Issue ID,Student APAAR,Student Name,Rule Code,Severity,Status,Message,Resolved By,Resolved At");

        List<ValidationIssue> issues = validationIssueRepository.findAll();
        for (ValidationIssue i : issues) {
            Student s = i.getStudent();
            pw.printf("%d,\"%s\",\"%s\",\"%s\",\"%s\",\"%s\",\"%s\",\"%s\",\"%s\"%n",
                    i.getId(),
                    s != null ? s.getMaskedApaarId() : "N/A",
                    s != null ? s.getName() : "N/A",
                    i.getRuleCode(),
                    i.getSeverity(),
                    i.getStatus(),
                    i.getMessage().replace("\"", "\"\""),
                    i.getResolvedBy() != null ? i.getResolvedBy() : "",
                    i.getResolvedAt() != null ? i.getResolvedAt().toString() : ""
            );
        }

        auditService.log(
                actor,
                role,
                "GENERATE_REPORT_CSV",
                "Report",
                institutionId != null ? institutionId.toString() : "ALL",
                ip,
                "Generated CSV Regulatory Summary Report"
        );

        return sw.toString();
    }

    public byte[] generateSummaryPdf(Long institutionId, Integer academicYear, String actor, String role, String ip) throws Exception {
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        Document document = new Document(PageSize.A4, 36, 36, 40, 40);
        PdfWriter.getInstance(document, baos);
        document.open();

        // Header Palette
        Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18, new Color(31, 73, 125));
        Font subTitleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12, new Color(0, 112, 192));
        Font normalFont = FontFactory.getFont(FontFactory.HELVETICA, 10, Color.DARK_GRAY);
        Font boldFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, Color.BLACK);
        Font tableHeaderFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, Color.WHITE);
        Font cellFont = FontFactory.getFont(FontFactory.HELVETICA, 8, Color.BLACK);

        // Header Title
        Paragraph title = new Paragraph("ALL INDIA COUNCIL FOR TECHNICAL EDUCATION", titleFont);
        title.setAlignment(Element.ALIGN_CENTER);
        document.add(title);

        Paragraph sub = new Paragraph("Regulation Bureau - APAAR-Connect Institutional Verification Report", subTitleFont);
        sub.setAlignment(Element.ALIGN_CENTER);
        sub.setSpacingAfter(8);
        document.add(sub);

        Paragraph meta = new Paragraph(String.format("Generated on %s by %s (%s)\nScope: %s",
                LocalDateTime.now().format(DateTimeFormatter.ofPattern("dd-MMM-yyyy HH:mm:ss")),
                actor, role,
                institutionId != null ? "Institution ID " + institutionId : "All Institutions across Regions"), normalFont);
        meta.setSpacingAfter(14);
        document.add(meta);

        // Section 1: Programme Enrolment Table
        Paragraph sec1 = new Paragraph("1. Approved Intake vs Actual Enrolment Analysis", boldFont);
        sec1.setSpacingAfter(6);
        document.add(sec1);

        PdfPTable table = new PdfPTable(7);
        table.setWidthPercentage(100);
        table.setWidths(new float[]{1.5f, 2.5f, 3.5f, 1.2f, 1.2f, 1.2f, 1.5f});

        String[] headers = {"Code", "Institution", "Programme", "Intake", "Quota", "Enrolled", "Status"};
        for (String h : headers) {
            PdfPCell cell = new PdfPCell(new Phrase(h, tableHeaderFont));
            cell.setBackgroundColor(new Color(31, 73, 125));
            cell.setPadding(5);
            cell.setHorizontalAlignment(Element.ALIGN_CENTER);
            table.addCell(cell);
        }

        List<Programme> programmes = institutionId != null ?
                programmeRepository.findByInstitutionId(institutionId) :
                programmeRepository.findAll();

        for (Programme p : programmes) {
            long actual = studentRepository.countByProgrammeId(p.getId());
            double util = p.getTotalPermittedIntake() > 0 ?
                    Math.round((double) actual / p.getTotalPermittedIntake() * 1000.0) / 10.0 : 0.0;
            String status = util > 100.0 ? "EXCEEDED (" + (int)util + "%)" : (util >= 90.0 ? "WARNING (" + (int)util + "%)" : "OK (" + (int)util + "%)");

            table.addCell(new PdfPCell(new Phrase(p.getInstitution().getCode(), cellFont)));
            table.addCell(new PdfPCell(new Phrase(p.getInstitution().getName(), cellFont)));
            table.addCell(new PdfPCell(new Phrase(p.getName(), cellFont)));
            table.addCell(new PdfPCell(new Phrase(String.valueOf(p.getApprovedIntake()), cellFont)));
            table.addCell(new PdfPCell(new Phrase(String.valueOf(p.getSupernumeraryQuota()), cellFont)));
            table.addCell(new PdfPCell(new Phrase(String.valueOf(actual), cellFont)));

            PdfPCell statusCell = new PdfPCell(new Phrase(status, cellFont));
            if (util > 100.0) {
                statusCell.setBackgroundColor(new Color(255, 230, 230));
            } else if (util >= 90.0) {
                statusCell.setBackgroundColor(new Color(255, 248, 220));
            }
            table.addCell(statusCell);
        }
        document.add(table);

        // Section 2: Exceptions and Regulatory Anomalies
        Paragraph sec2 = new Paragraph("\n2. Active Regulatory Exceptions and Anomalies", boldFont);
        sec2.setSpacingAfter(6);
        document.add(sec2);

        PdfPTable excTable = new PdfPTable(5);
        excTable.setWidthPercentage(100);
        excTable.setWidths(new float[]{1.5f, 2.0f, 2.5f, 1.5f, 4.5f});

        String[] excHeaders = {"Student APAAR", "Student Name", "Rule Code", "Status", "Details"};
        for (String h : excHeaders) {
            PdfPCell cell = new PdfPCell(new Phrase(h, tableHeaderFont));
            cell.setBackgroundColor(new Color(127, 95, 168)); // Accent purple
            cell.setPadding(5);
            cell.setHorizontalAlignment(Element.ALIGN_CENTER);
            excTable.addCell(cell);
        }

        List<ValidationIssue> issues = validationIssueRepository.findAll();
        int issueLimit = Math.min(issues.size(), 20); // Top 20 for PDF brevity
        for (int i = 0; i < issueLimit; i++) {
            ValidationIssue vi = issues.get(i);
            Student s = vi.getStudent();
            excTable.addCell(new PdfPCell(new Phrase(s != null ? s.getMaskedApaarId() : "N/A", cellFont)));
            excTable.addCell(new PdfPCell(new Phrase(s != null ? s.getName() : "N/A", cellFont)));
            excTable.addCell(new PdfPCell(new Phrase(vi.getRuleCode(), cellFont)));
            excTable.addCell(new PdfPCell(new Phrase(vi.getStatus(), cellFont)));
            excTable.addCell(new PdfPCell(new Phrase(vi.getMessage(), cellFont)));
        }
        document.add(excTable);

        // Footer note
        Paragraph footer = new Paragraph("\n* Notice: Prototype regulatory preview generated for Smart India Hackathon 2026. Data verified against simulated APAAR adapter.", normalFont);
        footer.setAlignment(Element.ALIGN_CENTER);
        document.add(footer);

        document.close();

        auditService.log(
                actor,
                role,
                "GENERATE_REPORT_PDF",
                "Report",
                institutionId != null ? institutionId.toString() : "ALL",
                ip,
                "Generated PDF Regulatory Summary Report"
        );

        return baos.toByteArray();
    }
}
