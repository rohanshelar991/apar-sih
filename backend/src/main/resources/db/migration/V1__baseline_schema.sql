-- Entity-aligned baseline. LocalDateTime remains TIMESTAMP WITHOUT TIME ZONE.

-- CHECK values: ValidationResult, ValidationEngine, ValidationIssueInfo,

-- ValidationService, IntakeService, and UploadService. Never modify after application.

CREATE TABLE institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(255) NOT NULL,
    state VARCHAR(64) NOT NULL,
    city VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE programmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id),
    name VARCHAR(100) NOT NULL,
    code VARCHAR(20) NOT NULL,
    academic_year INTEGER NOT NULL,
    approved_intake INTEGER NOT NULL,
    supernumerary_quota INTEGER NOT NULL
);

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apaar_id VARCHAR(16) NOT NULL,
    name VARCHAR(120) NOT NULL,
    dob DATE NOT NULL,
    gender VARCHAR(16) NOT NULL,
    programme_id BIGINT NOT NULL REFERENCES programmes(id),
    institution_id BIGINT NOT NULL REFERENCES institutions(id),
    admission_year INTEGER NOT NULL,
    category VARCHAR(32) NOT NULL,
    email VARCHAR(120),
    phone VARCHAR(20),
    verification_status VARCHAR(24) NOT NULL,
    consent_given BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ck_students_verification_status CHECK (verification_status IN ('VALID', 'PENDING', 'VERIFIED', 'DUPLICATE', 'ERROR')),
    CONSTRAINT ck_students_category CHECK (category IN ('REGULAR', 'SUPERNUMERARY', 'NRI', 'OCI', 'FOREIGN_NATIONAL'))
);

CREATE TABLE upload_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL REFERENCES institutions(id),
    filename VARCHAR(255) NOT NULL,
    total_rows INTEGER NOT NULL,
    valid_rows INTEGER NOT NULL,
    error_rows INTEGER NOT NULL,
    duplicate_rows INTEGER NOT NULL,
    uploaded_by VARCHAR(120) NOT NULL,
    uploaded_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(24) NOT NULL,
    CONSTRAINT ck_upload_batches_status CHECK (status IN ('PROCESSING', 'COMPLETED', 'FAILED'))
);

CREATE TABLE validation_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES students(id),
    upload_batch_id BIGINT REFERENCES upload_batches(id),
    rule_code VARCHAR(64) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    message VARCHAR(500) NOT NULL,
    suggested_fix VARCHAR(500),
    status VARCHAR(16) NOT NULL,
    resolved_by VARCHAR(120),
    resolved_at TIMESTAMP WITHOUT TIME ZONE,
    raw_record VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ck_validation_issues_severity CHECK (severity IN ('ERROR', 'WARNING', 'INFO')),
    CONSTRAINT ck_validation_issues_status CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED', 'ESCALATED', 'UNDER_REVIEW'))
);

CREATE TABLE student_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    field VARCHAR(64) NOT NULL,
    old_value VARCHAR(255),
    new_value VARCHAR(255),
    changed_by VARCHAR(120) NOT NULL,
    changed_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE verification_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    token VARCHAR(128) NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    allowed_fields VARCHAR(255) NOT NULL,
    created_by VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(120) NOT NULL,
    role VARCHAR(50) NOT NULL,
    action VARCHAR(64) NOT NULL,
    entity VARCHAR(64) NOT NULL,
    entity_id VARCHAR(64),
    ip VARCHAR(45),
    timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    details VARCHAR(1000)
);

CREATE TABLE user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(128) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    role VARCHAR(32) NOT NULL,
    institution_id BIGINT REFERENCES institutions(id),
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE verification_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id BIGINT NOT NULL REFERENCES verification_tokens(id),
    verifier_ip VARCHAR(45),
    verifier_agent VARCHAR(255),
    status VARCHAR(32) NOT NULL,
    requested_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
