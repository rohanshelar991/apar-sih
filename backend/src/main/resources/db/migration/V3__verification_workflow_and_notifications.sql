-- Review cases are distinct from verification_requests, which records public token lookups.
CREATE TABLE verification_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    submitted_by VARCHAR(120) NOT NULL,
    institution_id BIGINT NOT NULL REFERENCES institutions(id),
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    reviewer_email VARCHAR(120),
    remarks VARCHAR(1000),
    submitted_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_verification_cases_status CHECK (status IN ('PENDING','UNDER_REVIEW','APPROVED','REJECTED'))
);
CREATE INDEX idx_verification_cases_status_time ON verification_cases(status, submitted_at);
CREATE INDEX idx_verification_cases_institution ON verification_cases(institution_id, status);
CREATE INDEX idx_verification_cases_student ON verification_cases(student_id, submitted_at DESC);
CREATE UNIQUE INDEX uq_verification_cases_active_student ON verification_cases(student_id) WHERE status IN ('PENDING','UNDER_REVIEW');

CREATE TABLE verification_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES verification_cases(id),
    from_status VARCHAR(24),
    to_status VARCHAR(24) NOT NULL,
    actor_email VARCHAR(120) NOT NULL,
    remarks VARCHAR(1000),
    changed_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_verification_history_to_status CHECK (to_status IN ('PENDING','UNDER_REVIEW','APPROVED','REJECTED'))
);
CREATE INDEX idx_verification_history_case_time ON verification_history(case_id, changed_at DESC);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_email VARCHAR(120) NOT NULL,
    notification_type VARCHAR(32) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(500) NOT NULL,
    related_case_id BIGINT REFERENCES verification_cases(id),
    read_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_notifications_recipient_unread ON notifications(recipient_email, read_at, created_at DESC);
