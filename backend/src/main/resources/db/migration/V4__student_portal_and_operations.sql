-- Additive application features. V1-V3 remain immutable.
ALTER TABLE user_accounts
    ADD COLUMN student_id BIGINT REFERENCES students(id),
    ADD CONSTRAINT uq_user_accounts_student UNIQUE (student_id);

ALTER TABLE verification_cases
    ADD COLUMN priority VARCHAR(12) NOT NULL DEFAULT 'NORMAL',
    ADD COLUMN assigned_to VARCHAR(120),
    ADD CONSTRAINT ck_verification_cases_priority CHECK (priority IN ('LOW','NORMAL','HIGH','URGENT'));
CREATE INDEX idx_verification_cases_assignee ON verification_cases(assigned_to, status, submitted_at);

CREATE TABLE student_profile_update_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    requester_email VARCHAR(120) NOT NULL,
    requested_changes JSONB NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    reviewer_email VARCHAR(120),
    remarks VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT ck_student_profile_update_status CHECK (status IN ('PENDING','APPROVED','REJECTED'))
);
CREATE INDEX idx_profile_update_student_status ON student_profile_update_requests(student_id, status, created_at DESC);

CREATE TABLE student_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    uploaded_by VARCHAR(120) NOT NULL,
    document_type VARCHAR(32) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    content BYTEA NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    reviewer_email VARCHAR(120),
    reviewer_remarks VARCHAR(1000),
    uploaded_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT ck_student_documents_status CHECK (status IN ('PENDING','VERIFIED','REJECTED')),
    CONSTRAINT ck_student_documents_size CHECK (file_size > 0 AND file_size <= 10485760)
);
CREATE INDEX idx_student_documents_student ON student_documents(student_id, uploaded_at DESC);

CREATE TABLE announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    body VARCHAR(5000) NOT NULL,
    audience VARCHAR(24) NOT NULL DEFAULT 'ALL',
    institution_id BIGINT REFERENCES institutions(id),
    created_by VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITHOUT TIME ZONE,
    expires_at TIMESTAMP WITHOUT TIME ZONE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_announcements_audience CHECK (audience IN ('ALL','STUDENTS','INSTITUTION','STAFF'))
);
CREATE INDEX idx_announcements_active_date ON announcements(active, published_at DESC, expires_at);

CREATE TABLE announcement_reads (
    announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    user_email VARCHAR(120) NOT NULL,
    read_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (announcement_id, user_email)
);

CREATE TABLE notification_preferences (
    user_email VARCHAR(120) PRIMARY KEY,
    verification_updates BOOLEAN NOT NULL DEFAULT TRUE,
    assignments BOOLEAN NOT NULL DEFAULT TRUE,
    announcements BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
